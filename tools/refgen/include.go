package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// included are the pages whose body is a section of spin-terraform-aws's README, between its
// `<!-- BEGIN website:<page>` and `<!-- END website:<page> -->` markers: the procedure is the
// module's, reviewed where the module changes, and the site says it once, as the module does.
var included = []struct{ page, title, description string }{
	{"aws/update", "Update", "Move an installation to a new release, and what happens to its machines and workspaces while it rolls out."},
	{"aws/remove", "Remove", "Delete an installation on purpose: what refuses to be destroyed, why, and the steps to remove it anyway."},
}

const readme = "README.md"

// includedPages writes each included page from the README of the checkout tf, at commit.
func includedPages(tf, commit string) (map[string][]byte, error) {
	raw, err := os.ReadFile(filepath.Join(tf, readme))
	if err != nil {
		return nil, err
	}
	pages := map[string][]byte{}
	for _, p := range included {
		body, err := readmeSection(raw, p.page)
		if err != nil {
			return nil, err
		}
		pages[p.page+".md"] = []byte(fmt.Sprintf("---\ntitle: %q\ndescription: %q\nsource: %q\neditUrl: false\n---\n\n"+
			"<!-- Generated by tools/refgen from spin-terraform-aws's README.md. Edit the README, not this file. -->\n\n%s\n",
			p.title, p.description, "spin-terraform-aws:"+readme, moduleLinks(body, commit)))
	}
	return pages, nil
}

// readmeSection is what is between page's markers: the BEGIN comment, which says why it is
// there, is the README's and not the page's.
func readmeSection(raw []byte, page string) (string, error) {
	begin, end := "<!-- BEGIN website:"+page+" ", "<!-- END website:"+page+" -->"
	_, after, ok := bytes.Cut(raw, []byte(begin))
	if !ok {
		return "", fmt.Errorf("spin-terraform-aws's %s has no %q marker", readme, strings.TrimSpace(begin))
	}
	_, after, ok = bytes.Cut(after, []byte("-->"))
	if !ok {
		return "", fmt.Errorf("spin-terraform-aws's %s: the marker for %s is not closed", readme, page)
	}
	body, _, ok := bytes.Cut(after, []byte(end))
	if !ok {
		return "", fmt.Errorf("spin-terraform-aws's %s has no %q", readme, end)
	}
	if bytes.Contains(body, []byte("<!-- BEGIN website:")) {
		return "", fmt.Errorf("spin-terraform-aws's %s: %s's section holds another one's marker", readme, page)
	}
	return string(bytes.TrimSpace(body)), nil
}

// readmeLink is a Markdown link or image and its target.
var readmeLink = regexp.MustCompile(`(\]\()([^)\s]+)\)`)

// moduleLinks points the README's relative links - a path in the repository, from its root on
// GitHub when it starts with a slash, or an anchor of the README - at the repository, at commit:
// on the site a relative link would be a page of the site's, which there is not.
func moduleLinks(md, commit string) string {
	return readmeLink.ReplaceAllStringFunc(md, func(m string) string {
		target := readmeLink.FindStringSubmatch(m)[2]
		switch {
		case strings.Contains(target, "://"), strings.HasPrefix(target, "mailto:"):
			return m
		case strings.HasPrefix(target, "#"):
			target = readme + target
		}
		return fmt.Sprintf("](https://github.com/spin-stack/spin-terraform-aws/blob/%s/%s)", commit, strings.TrimLeft(strings.TrimPrefix(target, "./"), "/"))
	})
}
