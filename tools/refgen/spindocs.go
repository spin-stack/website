package main

import (
	"bytes"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// spinDocs are the pages that are a document of spin's, whole: what it says is reviewed in the
// change that makes it so, beside the code, and the site says it once, in spin's words. A page
// that restated one went stale release by release with nothing to fail on it. The title is the
// document's own heading; the description is the site's, being the page's line in llms.txt.
//
// The page is written outside reference/, so every check of a hand-written page reads it too: a
// command the document quotes that the CLI no longer has fails here, and is fixed in spin.
var spinDocs = []struct{ doc, page, description string }{
	{"docs/access.md", "use/access.md", "Who logs in to a workspace, the passkey that adds a key or a guest, and what a workspace applies of your settings."},
	{"docs/runners.md", "admin/runners.md", "What draining, cordoning, activating and revoking a runner do, what each leaves behind, and how to bring the capacity back."},
}

// spinDocPages writes each of spinDocs under docs from the checkout spin, at commit, and says
// which differ.
func spinDocPages(spin, commit, docs string, check bool) ([]string, error) {
	var stale []string
	for _, d := range spinDocs {
		raw, err := os.ReadFile(filepath.Join(spin, d.doc))
		if err != nil {
			return nil, err
		}
		title, body, err := titled(raw)
		if err != nil {
			return nil, fmt.Errorf("spin's %s: %w", d.doc, err)
		}
		body = shellFences(absoluteLinks(body, commit, path.Dir(d.doc)))
		source := "spin:" + d.doc
		page := fmt.Sprintf("---\ntitle: %q\ndescription: %q\nsource: %q\neditUrl: false\n---\n\n"+
			"<!-- Generated by tools/refgen from %s. Edit the source, not this file. -->\n\n%s\n",
			title, d.description, source, source, bytes.TrimSpace(body))
		at := filepath.Join(docs, d.page)
		differs, err := syncFile(at, []byte(page), check)
		if err != nil {
			return nil, err
		}
		if differs {
			stale = append(stale, at)
		}
	}
	return stale, nil
}

// titled splits a document into its first heading's words and what follows it: the heading is
// the page's title, which the site draws from the frontmatter.
func titled(raw []byte) (string, []byte, error) {
	first, rest, _ := bytes.Cut(bytes.TrimLeft(raw, "\n"), []byte("\n"))
	title, ok := strings.CutPrefix(string(first), "# ")
	if !ok || strings.TrimSpace(title) == "" {
		return "", nil, fmt.Errorf("does not start with a # heading")
	}
	return strings.TrimSpace(title), rest, nil
}

// shellFences names the language of a block spin's documents leave bare when every line of it
// is a spin command, so the page's commands are checked against the CLI as any page's are. A
// block of what a log says, or of another tool's commands, stays as it is.
func shellFences(raw []byte) []byte {
	lines := strings.Split(string(raw), "\n")
	for i := 0; i < len(lines); i++ {
		if !strings.HasPrefix(lines[i], "```") {
			continue
		}
		end := i + 1
		for end < len(lines) && !strings.HasPrefix(lines[end], "```") {
			end++
		}
		if lines[i] == "```" && end > i+1 && allSpin(lines[i+1:end]) {
			lines[i] = "```bash"
		}
		i = end
	}
	return []byte(strings.Join(lines, "\n"))
}

func allSpin(lines []string) bool {
	for _, l := range lines {
		if !strings.HasPrefix(l, "spin ") {
			return false
		}
	}
	return true
}
