/** A group in Starlight's sidebar shape. */
function group(g) {
	return g.groups
		? {
				label: g.label,
				items: g.groups.map(([label, directory]) => ({ label, collapsed: true, items: [{ autogenerate: { directory } }] })),
			}
		: { label: g.label, items: g.items.map(([label, slug]) => ({ label, slug })) };
}

/** The topics in starlight-sidebar-topics' shape, each with its groups. A group with no topic fails the build. */
export function sidebarTopics() {
	for (const g of nav) {
		if (!topics.some((t) => t.id === g.topic)) throw new Error(`src/lib/nav.mjs: group ${g.label} has no topic`);
	}
	return topics.map((t) => ({ ...t, items: nav.filter((g) => g.topic === t.id).map(group) }));
}
